#!/usr/bin/env bash
set -euo pipefail

# Follow symlinks without readlink -f, which macOS lacks before 12.3.
script=$0
while [ -L "$script" ]; do
    target=$(readlink -- "$script")
    case $target in
        /*) script=$target ;;
        *) script=$(dirname -- "$script")/$target ;;
    esac
done
CDPATH= cd -P -- "$(dirname -- "$script")/.."

# Virtual environments are handled by cleanup-venv.sh, node_modules is removed below.
prune=(\( -name .git -o -name node_modules -o -name '.venv*' -o -name 'venv*' -o -name env -o -name ENV -o -name env.bak \) -prune -o)

echo "🚀 Starting Python + Node dev cleanup..."

# ----- Python bytecode -----
echo "Removing __pycache__ and *.py[co]..."
find . "${prune[@]}" -type d -name "__pycache__" -exec rm -rf {} +
find . "${prune[@]}" -type f -name "*.py[co]" -exec rm -f {} +
find . "${prune[@]}" -type f -name '*$py.class' -exec rm -f {} +

# ----- Tool caches -----
echo "Removing Python tool caches..."
for cache in .mypy_cache .ruff_cache .pytest_cache .hypothesis .pytype .isort_cache .tox .nox .cache .pyre .pybuilder cython_debug __pypackages__; do
    [ -d "$cache" ] && rm -rf "$cache"
done

for file in .dmypy.json dmypy.json; do
    [ -f "$file" ] && rm -f "$file"
done

# ----- Build artifacts -----
echo "Removing build artifacts..."
for build in .Python build develop-eggs dist downloads eggs .eggs lib64 parts sdist var wheels share/python-wheels target out site docs/_build *.egg; do
    [ -e "$build" ] && rm -rf "$build"
done

for file in .installed.cfg MANIFEST; do
    [ -e "$file" ] && rm -rf "$file"
done

find . "${prune[@]}" -type f \( -name '*.so' -o -name '*.manifest' \) -exec rm -f {} +
find . "${prune[@]}" -type d -name "*.egg-info" -exec rm -rf {} +

# ----- IDE / project folders -----
echo "Removing IDE folders..."
for ide in .ipynb_checkpoints profile_default .spyderproject .spyproject .ropeproject; do
    [ -d "$ide" ] && rm -rf "$ide"
done

# Remove transient files generated by workspace-scoped zsh config.
if [ -d ".vscode/zsh" ]; then
    echo "Removing zsh transient files (.zcompdump*, .zsh_sessions*)..."
    find .vscode/zsh -maxdepth 1 -type f \( -name '.zcompdump*' -o -name '.zsh_sessions*' \) -delete
fi

# ----- Coverage files -----
echo "Removing coverage files..."
for coverage in .coverage coverage.xml cov.xml nosetests.xml; do
    [ -f "$coverage" ] && rm -f "$coverage"
done

for coverage_dir in htmlcov cover; do
    [ -e "$coverage_dir" ] && rm -rf "$coverage_dir"
done

find . -maxdepth 1 -type f \( -name '.coverage.*' -o -name '*.cover' -o -name '*.py,cover' \) -delete

# ----- Runtime / local files -----
echo "Removing runtime and local files..."
for runtime_dir in instance .webassets-cache .scrapy; do
    [ -d "$runtime_dir" ] && rm -rf "$runtime_dir"
done

for runtime_file in celerybeat-schedule celerybeat.pid pip-log.txt pip-delete-this-directory.txt; do
    [ -e "$runtime_file" ] && rm -rf "$runtime_file"
done

find . "${prune[@]}" -type f \( -name '*.mo' -o -name '*.log' \) -exec rm -f {} +

# ----- Local config files -----
purge=()
for local_file in .env local_settings.py .idea ipython_config.py db.sqlite3 db.sqlite3-journal; do
    [ -e "$local_file" ] && purge+=("$local_file")
done

# Only a terminal counts as confirmation; piped input keeps the files.
if [ -t 0 ] && [ "${#purge[@]}" -gt 0 ]; then
    echo ""
    read -p "Do you want to purge local config files (${purge[*]})? (y/n) " -n 1 -r || REPLY=n
    echo
    if [[ $REPLY =~ ^[Yy]$ ]]; then
        echo "Removing local config files..."
        rm -rf "${purge[@]}"
    fi
fi

# ----- Node.js -----
echo "Removing Node.js..."
if [ -d "node_modules" ]; then
    rm -rf node_modules
    echo "⚠️  The commit-msg hook needs node_modules: run 'npm ci' before your next commit."
fi

echo "✅ Cleanup complete!"
